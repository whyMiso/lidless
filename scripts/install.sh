#!/usr/bin/env bash
# Lidless installer: builds from source, signs with YOUR Apple certificate, installs the app.
# Designed to be run unattended by a person or an AI coding agent. See AGENTS.md.
#
#   scripts/install.sh                 build + install to /Applications + launch
#   scripts/install.sh --dest DIR      install somewhere else (testing; the helper needs /Applications)
#   scripts/install.sh --no-launch     don't open the app afterwards
#   scripts/install.sh --identity "Apple Development: …"   pick a specific signing identity
#   scripts/install.sh --uninstall     restore settings, unregister the helper, remove the app
#
# Exit codes: 0 ok · 2 unsupported system / Xcode missing · 3 no signing certificate · 4 build failed
set -euo pipefail
cd "$(dirname "$0")/.."

DEST=/Applications
LAUNCH=1
IDENTITY="${LIDLESS_SIGN_IDENTITY:-}"
UNINSTALL=0
while [ $# -gt 0 ]; do
    case "$1" in
        --dest) DEST="$2"; shift 2 ;;
        --no-launch) LAUNCH=0; shift ;;
        --identity) IDENTITY="$2"; shift 2 ;;
        --uninstall) UNINSTALL=1; shift ;;
        -h|--help) sed -n '2,13p' "$0"; exit 0 ;;
        *) echo "unknown option: $1" >&2; exit 1 ;;
    esac
done

say()  { printf '\033[1m==> %s\033[0m\n' "$*"; }
fail() { local code=$1; shift; printf '\033[31mERROR:\033[0m %s\n' "$*" >&2; exit "$code"; }

# ---------------------------------------------------------------- uninstall
if [ "$UNINSTALL" = 1 ]; then
    APP="$DEST/Lidless.app"
    [ -d "$APP" ] || fail 1 "$APP not found"
    say "Quitting Lidless (this restores sleep settings and fans)"
    osascript -e 'tell application id "dev.lidless.Lidless" to quit' 2>/dev/null || true
    sleep 2
    say "Unregistering the helper (it restores everything on the way out)"
    open -W -a "$APP" --args --uninstall-helper || true
    say "Removing $APP"
    rm -rf "$APP"
    echo "Done. If '/Library/Application Support/Lidless' exists it's empty and can be removed with:"
    echo "  sudo rm -rf '/Library/Application Support/Lidless'"
    exit 0
fi

# ---------------------------------------------------------------- 1. system checks
say "Checking system"
MAJOR="$(sw_vers -productVersion | cut -d. -f1)"
[ "$MAJOR" -ge 14 ] || fail 2 "macOS 14 or later is required (found $(sw_vers -productVersion))."
if ! grep -q "\.app/Contents/Developer" <<<"$(xcode-select -p 2>/dev/null || true)"; then
    fail 2 "Full Xcode is required (not just the Command Line Tools).
  1. Install Xcode from the App Store (free).
  2. Run: sudo xcode-select -s /Applications/Xcode.app/Contents/Developer
  3. Open Xcode once to accept the license, then re-run this script."
fi
xcodebuild -version | sed -n 1p

# ---------------------------------------------------------------- 2. signing identity
# A privileged helper must be signed by a real Apple certificate with a Team ID; the app and the
# helper verify each other's Team ID over XPC. Any of these work:
#   "Developer ID Application" (paid account), or "Apple Development" (free Apple ID in Xcode).
say "Finding a code-signing certificate"
IDENTITIES="$(security find-identity -v -p codesigning | grep -oE '"[^"]+"' | tr -d '"' || true)"
if [ -z "$IDENTITY" ]; then
    IDENTITY="$(grep -m1 '^Developer ID Application:' <<<"$IDENTITIES" || true)"
    [ -n "$IDENTITY" ] || IDENTITY="$(grep -m1 '^Apple Development:' <<<"$IDENTITIES" || true)"
fi
if [ -z "$IDENTITY" ]; then
    fail 3 "No Apple code-signing certificate found. A free Apple ID is enough:
  1. Open Xcode → Settings… → Accounts → '+' → Apple ID, and sign in.
  2. Select your account/team → Manage Certificates… → '+' → Apple Development.
  3. Re-run this script.
(The certificate stays in your login keychain; this script never sees your Apple ID.)"
fi
grep -qxF "$IDENTITY" <<<"$IDENTITIES" || fail 3 "Signing identity not found in keychain: $IDENTITY"
# The Team ID is the certificate's OU field. (For "Apple Development" certificates the code in
# parentheses in the name is NOT the Team ID.)
TEAM_ID="$(security find-certificate -c "$IDENTITY" -p | openssl x509 -noout -subject \
    | grep -oE 'OU ?= ?[A-Z0-9]{10}' | grep -oE '[A-Z0-9]{10}$' || true)"
[ -n "$TEAM_ID" ] || fail 3 "Could not read a Team ID from certificate: $IDENTITY"
echo "Using: ${IDENTITY%% (*} (team $TEAM_ID)"

LOCAL=Config/Local.xcconfig
MARKER="// generated by scripts/install.sh"
if [ -f "$LOCAL" ] && ! grep -qF "$MARKER" "$LOCAL"; then
    echo "Keeping your hand-written $LOCAL"
else
    printf '%s\nDEVELOPMENT_TEAM = %s\nCODE_SIGN_IDENTITY = %s\n' "$MARKER" "$TEAM_ID" "$IDENTITY" > "$LOCAL"
fi

# ---------------------------------------------------------------- 3. build
say "Building Lidless (Release, $(uname -m)) — takes a minute or two"
if command -v xcodegen >/dev/null 2>&1; then xcodegen generate --quiet >/dev/null 2>&1 || true; fi
DD=build/install
LOG=build/install-build.log
mkdir -p build
if ! xcodebuild -project Lidless.xcodeproj -scheme Lidless -configuration Release \
        -derivedDataPath "$DD" ARCHS="$(uname -m)" ONLY_ACTIVE_ARCH=YES build >"$LOG" 2>&1; then
    grep -E "error:" "$LOG" | sort -u | sed -n "1,20p" >&2 || true
    fail 4 "Build failed. Full log: $LOG"
fi
BUILT="$DD/Build/Products/Release/Lidless.app"

say "Verifying signatures"
codesign --verify --deep --strict "$BUILT"
codesign -v -R="anchor apple generic and identifier \"dev.lidless.helper\" and certificate leaf[subject.OU] = \"$TEAM_ID\"" \
    "$BUILT/Contents/MacOS/LidlessHelper"
codesign -v -R="anchor apple generic and identifier \"dev.lidless.Lidless\" and certificate leaf[subject.OU] = \"$TEAM_ID\"" "$BUILT"
echo "App and helper are signed by team $TEAM_ID and accept each other."

# ---------------------------------------------------------------- 4. install
say "Installing to $DEST"
mkdir -p "$DEST"
# Quit only the copy we're replacing (quitting restores sleep + fan settings via the helper).
TARGET="$DEST/Lidless.app/Contents/MacOS/Lidless"
for pid in $(pgrep -x Lidless || true); do
    if [ "$(ps -o comm= -p "$pid")" = "$TARGET" ]; then
        kill -TERM "$pid" 2>/dev/null || true
        for _ in 1 2 3 4 5; do kill -0 "$pid" 2>/dev/null || break; sleep 1; done
        kill -9 "$pid" 2>/dev/null || true
    fi
done
rm -rf "$DEST/Lidless.app"
ditto "$BUILT" "$DEST/Lidless.app"
echo "Installed $DEST/Lidless.app"

if [ "$LAUNCH" = 1 ]; then open "$DEST/Lidless.app"; fi

cat <<EOF

✅ Lidless is installed.

Remaining steps need the person at the Mac (they're macOS security prompts):
  1. Click the Lidless icon in the menu bar (an eye) → "Install Helper…".
  2. In System Settings → General → Login Items & Extensions, allow "Lidless".
  3. Optional: Settings… → General → "Launch at login".

Keep Awake works immediately; lid-closed mode and fan control need the helper (steps 1–2).
To uninstall later: scripts/install.sh --uninstall
EOF
